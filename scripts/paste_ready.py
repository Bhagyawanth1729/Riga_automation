#!/usr/bin/env python3
"""Emit copy-paste blocks that match the Snorkel Riga Submission UI fields."""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from riga_lib import parse_task
from validate_submission import check_acceptance


def emit(task: dict) -> str:
    meta = task["meta"]
    lines = [
        f"# Paste sheet — {meta.get('id', '')}",
        "",
        "## 1. Left pane — Enter your prompt here",
        "Run this against both hard models. At least one must miss it consistently.",
        "If you see 'No Response was generated by the model', re-run. That is not a miss.",
        "",
        task["problem"],
        "",
        "## 2. Problem (Prompt)  [Write / LaTeX Preview]  — use Paste from Prompt",
        "",
        task["problem"],
        "",
        f"## 3. Domain = {meta.get('field')} / {meta.get('domain')}",
        f"## 4. Sub-domain = {meta.get('subdomain')}",
        "",
        "## 5. Domain Explanation",
        "",
        task["domain_explanation"],
        "",
        "## 6. Worked Solution  (one box per step; each body starts with Step N)",
        "",
    ]
    for step in task["steps"]:
        lines.append(f"### Box {step['n']}")
        lines.append(step["text"])
        lines.append("")
    lines.extend(
        [
            "## 7. Answer  (no \\boxed; wrap in $...$ only)",
            "",
            task["answer"],
            "",
            "## 8. In-App Evaluation — Check Accuracy of LaTeX  (mandatory)",
            "",
            f"## 9. Problem Type = {meta.get('problem_type')}",
            f"## 10. Answer Type = {meta.get('answer_type')}",
            "## 11. Concepts (1–5)",
        ]
    )
    for c in meta.get("concepts") or []:
        lines.append(f"- {c}")
    lines.extend(
        [
            "",
            "## 12. Submission Routing",
            "Use Automated Checks Only first. Switch to Quality Review only after:",
            "- at least one hard model misses consistently",
            "- in-app LaTeX check is clean",
            "- local qa_gate.py PASSes",
            f"Suggested routing: {meta.get('routing', 'Automated Checks Only')}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    if len(sys.argv) < 2:
        print("usage: paste_ready.py path/to/task.md")
        return 2
    path = Path(sys.argv[1])
    task = parse_task(path)
    errors = check_acceptance(task)
    blocking = [e for e in errors if not e.startswith("Voice:")]
    if task["meta"].get("status") != "ready":
        blocking.append("status must be 'ready' before emitting a paste sheet")
    if task["meta"].get("independently_verified") is not True:
        blocking.append("independently_verified must be true before emitting a paste sheet")
    if blocking:
        print("Refusing paste sheet — fix acceptance errors first:\n")
        for e in blocking:
            print(f"  - {e}")
        return 1
    out = path.with_name("PASTE.md")
    text = emit(task)
    out.write_text(text)
    print(text)
    print(f"\nwrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
