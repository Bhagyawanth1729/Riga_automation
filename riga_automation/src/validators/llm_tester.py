"""LLM difficulty tester for Project Riga.

Tests problems against frontier models to verify difficulty:
- Must stump at least ONE frontier model the MAJORITY of the time
- 'No response generated' does NOT count as an incorrect answer
- Runs N trials per model, computes failure rate
"""
from __future__ import annotations

import os
import time
from dataclasses import dataclass, field
from typing import Callable, Optional


@dataclass
class ModelAttempt:
    model: str
    trial: int
    raw_response: str
    extracted_answer: Optional[str]
    correct: Optional[bool]   # None => no response / could not extract
    latency_s: float = 0.0


@dataclass
class StumpReport:
    model: str
    trials: int
    wrong: int
    no_response: int
    failure_rate: float       # wrong / (trials - no_response)
    stumped: bool             # failure_rate >= threshold

    def summary(self) -> str:
        return (f"{self.model}: {self.wrong} wrong / {self.trials} trials "
                f"({self.no_response} no-response; failures don't count no-response), "
                f"failure rate {self.failure_rate:.0%} -> "
                f"{'STUMPED' if self.stumped else 'SOLVED'}")


SYSTEM_PROMPT = (
    "You are an expert scientist answering a single STEM problem. "
    "Give the final answer only, exactly as requested in the problem statement, "
    "at the end of your response on a line starting with 'ANSWER:'."
)


class LLMTester:
    """Pluggable multi-model tester. Provider clients injected by caller.

    Usage:
        tester = LLMTester()
        tester.register_provider("gpt-4.1", my_openai_fn)
        tester.register_provider("claude-opus", my_anthropic_fn)
        reports = tester.test(problem_prompt, reference_answer, trials=5)
    """

    def __init__(self, failure_threshold: float = 0.5,
                 answer_matcher: Optional[Callable[[str, str], bool]] = None):
        self.providers: dict[str, Callable[[str, str], str]] = {}
        self.failure_threshold = failure_threshold
        self.matcher = answer_matcher or self._default_matcher

    def register_provider(self, name: str, fn: Callable[[str, str], str]):
        """fn(system_prompt, user_prompt) -> raw response text"""
        self.providers[name] = fn

    @staticmethod
    def extract_answer(response: str) -> Optional[str]:
        import re
        m = re.search(r"ANSWER:\s*(.+)$", response.strip(), re.S | re.M)
        return m.group(1).strip() if m else None

    @staticmethod
    def _default_matcher(candidate: str, reference: str) -> bool:
        def norm(s: str) -> str:
            s = s.strip().strip("$").strip()
            return re.sub(r"\s+", "", s).lower()
        import re
        return norm(candidate) == norm(reference)

    def _run_once(self, fn, prompt: str) -> ModelAttempt:
        t0 = time.time()
        try:
            resp = fn(SYSTEM_PROMPT, prompt)
        except Exception as e:  # provider error -> count as no response
            return ModelAttempt("", -1, f"ERROR: {e}", None, None, time.time() - t0)
        lat = time.time() - t0
        ans = self.extract_answer(resp or "")
        return ModelAttempt("", -1, resp or "", ans, None, lat)

    def test_model(self, name: str, prompt: str, reference_answer: str,
                   trials: int = 5) -> StumpReport:
        fn = self.providers[name]
        wrong, no_resp = 0, 0
        attempts: list[ModelAttempt] = []
        for i in range(trials):
            att = self._run_once(fn, prompt)
            att.model, att.trial = name, i + 1
            if att.extracted_answer is None:
                # Per documentation: 'No Response was generated by the model'
                # is NOT equivalent to an incorrect answer -> excluded from rate
                att.correct = None
                no_resp += 1
            else:
                att.correct = self.matcher(att.extracted_answer, reference_answer)
                if not att.correct:
                    wrong += 1
            attempts.append(att)
        usable = trials - no_resp
        rate = (wrong / usable) if usable else 0.0
        return StumpReport(name, trials, wrong, no_resp, rate,
                           usable > 0 and rate >= self.failure_threshold)

    def test(self, prompt: str, reference_answer: str, trials: int = 5
             ) -> dict[str, StumpReport]:
        return {name: self.test_model(name, prompt, reference_answer, trials)
                for name in self.providers}
